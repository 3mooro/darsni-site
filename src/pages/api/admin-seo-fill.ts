export const GET: APIRoute = async ({ url }) => {
  if (url.searchParams.get('key') !== KEY) {
    return new Response('Forbidden', { status: 403 });
  }
  const db = env.DB;
  if (!db) return new Response('No DB', { status: 500 });

  // Make sure the imageAlt column exists (older schema may not have it)
  try { await db.prepare('ALTER TABLE blog ADD COLUMN imageAlt TEXT').run(); } catch {}

  if (url.searchParams.get('run') !== '1') {
    const { results } = await db.prepare('SELECT slug, description, imageAlt FROM blog ORDER BY created_at DESC').all();
    const rows = results || [];
    const missingDesc = rows.filter((r: any) => !r.description || String(r.description).trim().length < 40).length;
    const missingAlt = rows.filter((r: any) => !r.imageAlt || String(r.imageAlt).trim() === '').length;
    return Response.json({ mode: 'report', total: rows.length, missingDesc, missingAlt });
  }

  const report: any[] = [];
  for (const [slug, data] of Object.entries(SEO_DATA)) {
    const row: any = await db.prepare('SELECT id FROM blog WHERE slug = ?').bind(slug).first();
    if (!row) {
      report.push({ slug, status: 'not-found' });
      continue;
    }
    await db.prepare('UPDATE blog SET description = ?, imageAlt = ? WHERE id = ?')
      .bind(data.description, data.imageAlt, row.id).run();
    report.push({ slug, status: 'updated' });
  }
  const updated = report.filter(r => r.status === 'updated').length;
  return Response.json({ mode: 'run', updated, total: report.length, report });
};
